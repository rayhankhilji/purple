#!/usr/bin/env node
// PURPLE concept - regenerates concept/sim/fitted.js:
//   1. baseline estimate: 4 unpublished physical parameters estimated on ONE lap (the pole lap's speed trace, fit.calibrate)
//   2. competitor model: per-team CLA / CDA scale + per-PU ICE scale from each team's best qualifying lap time and trap only
//   3. held-out check: every team car against that team's real telemetry lap (trace RMS, sectors, corner minima)
// Usage: node concept/sim/build-fit.js [telemetry-dir] [--check]   (telemetry-dir default: concept/data/telemetry)
// Deterministic: the same code + data give a byte-identical file (no timestamps). Takes ~1 minute.
"use strict";
const fs = require("fs"), path = require("path");
const S = require("./lapsim.js"), F = require("./fit.js");

const OUT = path.join(__dirname, "fitted.js");
const args = process.argv.slice(2), check = args.includes("--check");
const dir = args.find(a => !a.startsWith("--")) || path.join(__dirname, "..", "data", "telemetry");
const weekend = S.loadWeekendConditions();
const conditions = weekend ? Object.assign({}, S.DEFAULT_CONDITIONS, weekend) : Object.assign({}, S.DEFAULT_CONDITIONS);
delete conditions.source;
const t0 = Date.now();
const est = F.calibrate({ conditions });
const pre = { baseline_estimate: est.estimate };
const base = F.baseOf(pre);
const teams = F.fitTeams({ conditions, car: base, cal: { grip_scale: 1, drag_scale: 1 } });
const held = fs.existsSync(dir) ? F.heldOut(Object.assign({}, pre, teams, { reference_driver: est.fit_lap.driver, global: { grip_scale: 1, drag_scale: 1 } }), dir, { conditions }) : [];
const b = S.simulateLap(base, "silverstone", conditions, { cal: { grip_scale: 1, drag_scale: 1 } });

const fit = {
  label: S.LABEL,
  note: "The baseline's unpublished parameters (tyre friction, CLA, CDA, load sensitivity) are estimated on one lap (the 2026 British GP pole lap's speed trace); " +
    "no correction factor sits on top (global = 1). Team cars are INFERRED from public best qualifying laps and speed traps, not team data; their real telemetry laps are a held-out check.",
  conditions,
  conditions_source: weekend ? weekend.source : "documented defaults (concept/sim/lapsim.js DEFAULT_CONDITIONS = 2026 British GP qualifying)",
  global: { grip_scale: 1, drag_scale: 1 },
  reference_driver: est.fit_lap.driver,
  baseline_estimate: est.estimate,
  baseline_estimate_scales: est.scales,
  calibration: { method: est.method, fit_lap: est.fit_lap, prior_check: est.prior_check, derived_agreement: est.derived_agreement },
  baseline: { lap_s: b.lap_s, sectors_s: b.sectors_s, vmax_kmh: b.vmax_kmh, speed_trap_kmh: b.speed_trap_kmh, vmin_kmh: b.vmin_kmh, energy: b.energy, speeds_kmh: b.speeds_kmh },
  team_fit: { iterations: teams.iterations, cost: teams.cost, sigma: teams.settings.sigma, bounds: teams.settings.bounds, pu_scale: teams.pu_scale },
  teams: teams.teams.map(t => Object.assign({}, t, { heldout: held.find(h => h.team === t.team) || null })),
};
const body = "// GENERATED by concept/sim/build-fit.js - do not edit by hand. PURPLE concept lap-sim estimates + inferred team cars.\n" +
  "// " + S.LABEL + "\n" +
  "// Team cars are inferred from public 2026 British GP qualifying laps and speed traps, not team data.\n" +
  "(function () {\n  const FIT = " + JSON.stringify(fit, null, 1).replace(/\n/g, "\n  ") + ";\n" +
  "  const root = typeof window !== \"undefined\" ? window : globalThis;\n  root.EI = root.EI || {}; root.EI.CONCEPT_SIM_FIT = FIT;\n" +
  "  if (typeof module !== \"undefined\" && module.exports) module.exports = FIT;\n})();\n";

if (check) {
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8") === body;
  console.log(same ? "fitted.js is up to date" : "fitted.js differs from a fresh fit");
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(OUT, body);
console.log("wrote", path.relative(process.cwd(), OUT), "in", ((Date.now() - t0) / 1000).toFixed(1) + " s");
console.log("baseline estimate scales", JSON.stringify(est.scales), "fit lap", JSON.stringify(est.fit_lap));
console.log("team".padEnd(13), "drv", "q_real ", "q_sim  ", "d_lap ", "trap_r", "trap_s", "d_trap", "cla   ", "cda   ", "pu    ", "bound | HELD-OUT: rms  sector residuals");
for (const t of fit.teams) {
  const h = t.heldout;
  console.log(t.team.padEnd(13), t.driver, t.q_real_s.toFixed(3), t.q_sim_s.toFixed(3), t.residual_lap_s.toFixed(3).padStart(6), t.trap_real_kmh.toFixed(1), t.trap_sim_kmh.toFixed(1), t.residual_trap_kmh.toFixed(1).padStart(6), t.cla_scale.toFixed(3), t.cda_scale.toFixed(3), t.pu_scale.toFixed(3), (t.at_bound.join(",") || "-").padEnd(5), "|", h ? h.trace_rms_kmh.toFixed(1) + "  " + h.sector_residuals_s.join(" / ") : "no telemetry");
}
console.log("pu_scale", JSON.stringify(teams.pu_scale));
