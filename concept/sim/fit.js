// PURPLE concept - lap-sim calibration and the competitor model (docs/concept/SIM.md §5-6).
// calibrate(): estimates the baseline car's unpublished parameters (tyre friction, CLA, CDA, load sensitivity) on ONE lap - the
// real 2026 British GP pole lap's speed trace (OpenF1) - with no correction factors on top. heldOut(): checks the other teams'
// real laps, which were not used except for their lap time and trap.
// fitTeams(): infers each team's car from public numbers only - its best qualifying lap and that driver's qualifying speed trap -
// with two parameters per team (CLA scale, CDA scale) and one per power-unit maker (ICE power scale, shared by customer teams),
// regularised towards the baseline (maximum a posteriori with stated priors and hard bounds). This is NOT team data.
// teamCar(id) / teamCars(): the fitted cars from concept/sim/fitted.js (generated by concept/sim/build-fit.js).
// Dual browser / Node: attaches to window.EI.conceptSimFit and to module.exports.
(function () {
  const root = typeof window !== "undefined" ? window : globalThis;
  const EI = (root.EI = root.EI || {});
  const T = EI.conceptSimTrack || require("./track.js");
  const S = EI.conceptSim && EI.conceptSim.simulateLap ? EI.conceptSim : require("./lapsim.js");

  const TEAM_FIT = {
    sigma: { lap_s: 0.10, trap_kmh: 1.0, cla: 0.12, cda: 0.10, pu: 0.03 },          // likelihood widths and prior widths (log scale)
    bounds: { cla: [0.70, 1.15], cda: [0.80, 1.25], pu: [0.92, 1.05] },
    iters: 14, lambda0: 1e-2, fd: 0.01,
  };

  function gameData() {
    const rp = EI.RACEPACE || T.loadGameData("racepace2026").RACEPACE;
    const se = EI.SEASON || T.loadGameData("season2026").SEASON;
    return { rp, se };
  }
  function reference(trackId) {
    const { rp } = gameData(), d = rp[trackId || "silverstone"];
    if (!d) throw new Error("concept sim: no EI.RACEPACE." + trackId);
    return { lap_s: d.pole.s, driver: d.pole.code, trap_kmh: d.speedTrapQuali[d.pole.code], race_trap_max_kmh: Math.max.apply(null, Object.values(d.speedTrap)) };
  }
  // per team: the driver with the team's best qualifying lap, that lap, and that driver's qualifying speed trap
  function teamTargets(trackId) {
    const { rp, se } = gameData(), d = rp[trackId || "silverstone"];
    return se.teams.map(t => {
      const seat = d.seat || {};
      const drivers = Object.keys(d.q).filter(code => (seat[code] ? seat[code] === t.id : t.drivers.indexOf(code) >= 0));
      drivers.sort((a, b) => d.q[a] - d.q[b]);
      const best = drivers[0];
      return { team: t.id, name: t.name, chassis: t.chassis, pu: t.pu, driver: best, q_s: d.q[best], trap_kmh: d.speedTrapQuali[best] };
    }).filter(x => x.driver);
  }

  function scaledCar(base, p, meta) {
    const c = JSON.parse(JSON.stringify(base));
    for (const m of ["corner", "straight"]) { c.aero[m].CLA_front_m2 *= p.cla_scale; c.aero[m].CLA_rear_m2 *= p.cla_scale; c.aero[m].CDA_m2 *= p.cda_scale; }
    c.pu.ice_kw *= p.pu_scale;
    if (meta) { c.id = meta.id; c.label = meta.label; }
    return c;
  }

  // small dense solver (Gaussian elimination with partial pivoting)
  function solve(A, b) {
    const n = b.length, M = A.map((r, i) => r.concat([b[i]]));
    for (let k = 0; k < n; k++) {
      let p = k; for (let i = k + 1; i < n; i++) if (Math.abs(M[i][k]) > Math.abs(M[p][k])) p = i;
      [M[k], M[p]] = [M[p], M[k]];
      for (let i = k + 1; i < n; i++) { const f = M[i][k] / M[k][k]; for (let j = k; j <= n; j++) M[i][j] -= f * M[k][j]; }
    }
    const x = new Array(n).fill(0);
    for (let i = n - 1; i >= 0; i--) { let s = M[i][n]; for (let j = i + 1; j < n; j++) s -= M[i][j] * x[j]; x[i] = s / M[i][i]; }
    return x;
  }
  const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);

  // ---- baseline estimation (the "calibration"): the parameters nobody publishes - tyre friction scale (mu_x, mu_y), corner +
  // straight CLA scale, corner + straight CDA scale and tyre load sensitivity - estimated on ONE lap, the pole lap's speed trace
  // (OpenF1, concept/sim/line-silverstone.js reference). Objective: mean squared speed error on the 5 m grid + (5 km/h per s)^2
  // x lap-time error^2. Nelder-Mead in log space, fixed iteration count -> deterministic. Speeds are never fitted point by
  // point: 4 global numbers move the whole lap. Other teams' laps are held out (heldOut()).
  function traceError(r, ref, tr) {
    let e2 = 0; const N = ref.d.length, n = r.trace.v_kmh.length;
    for (let k = 0; k < N; k++) { const i = Math.min(n - 1, Math.round(ref.d[k] / tr.ds)); e2 += (r.trace.v_kmh[i] - ref.ref_v_kmh[k]) ** 2; }
    return Math.sqrt(e2 / N);
  }
  function nelderMead(f, x0, step, iters) {
    let S = [x0]; for (let i = 0; i < x0.length; i++) { const x = x0.slice(); x[i] += step; S.push(x); }
    let F = S.map(f); const n = x0.length;
    for (let it = 0; it < iters; it++) {
      const idx = F.map((v, i) => i).sort((a, b) => F[a].f - F[b].f || a - b); S = idx.map(i => S[i]); F = idx.map(i => F[i]);
      const c = new Array(n).fill(0); for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) c[j] += S[i][j] / n;
      const xr = c.map((v, j) => v + (v - S[n][j])), fr = f(xr);
      if (fr.f < F[0].f) { const xe = c.map((v, j) => v + 2 * (v - S[n][j])), fe = f(xe); if (fe.f < fr.f) { S[n] = xe; F[n] = fe; } else { S[n] = xr; F[n] = fr; } }
      else if (fr.f < F[n - 1].f) { S[n] = xr; F[n] = fr; }
      else { const xc = c.map((v, j) => v + 0.5 * (S[n][j] - v)), fc = f(xc); if (fc.f < F[n].f) { S[n] = xc; F[n] = fc; } else { for (let i = 1; i <= n; i++) { S[i] = S[i].map((v, j) => S[0][j] + 0.5 * (v - S[0][j])); F[i] = f(S[i]); } } }
    }
    const idx = F.map((v, i) => i).sort((a, b) => F[a].f - F[b].f || a - b);
    return F[idx[0]];
  }
  const EST = { iters: 320, step: 0.15, lap_weight: 25, prior_sigma: [0.15, 0.3, 0.3, 0.7], prior_weight: 10 };   // [mu, CLA, CDA, load_sens]
  function estimatedCar(prior, x) {
    const c = JSON.parse(JSON.stringify(prior)), [mu, cla, cda, ls] = x.map(Math.exp);
    for (const m of ["corner", "straight"]) { c.aero[m].CLA_front_m2 *= cla; c.aero[m].CLA_rear_m2 *= cla; c.aero[m].CDA_m2 *= cda; }
    c.tyres.mu_x *= mu; c.tyres.mu_y *= mu; c.tyres.load_sens *= ls;
    return c;
  }
  function calibrate(opts) {
    opts = opts || {};
    const trackId = opts.trackId || "silverstone", tr = T.buildTrack(trackId), ref = opts.reference || tr.reference;
    if (!ref) throw new Error("concept sim: calibrate needs the telemetry reference lap (concept/sim/line-" + trackId + ".js)");
    const prior = opts.prior || S.priorCar(), cond = opts.conditions || {}, ident = { grip_scale: 1, drag_scale: 1 };
    if (ref.gearing_estimate) prior.gearing = ref.gearing_estimate;
    const f = x => {
      const car = estimatedCar(prior, x), r = S.simulateLap(car, trackId, cond, { trace: true, cal: ident });
      const rms = traceError(r, ref, tr);
      // MAP: log-normal priors around the sourced prior car keep weakly identified directions (e.g. CLA vs rolling load) at
      // physically plausible values; widths EST.prior_sigma (log scale), weight EST.prior_weight (km/h^2 per sigma^2)
      const pen = x.reduce((p, v, i) => p + (v / EST.prior_sigma[i]) ** 2, 0) * EST.prior_weight;
      return { f: rms * rms + EST.lap_weight * (r.lap_s - ref.reference.lap_s) ** 2 + pen, rms, r, car, x };
    };
    const best = nelderMead(f, [0, 0, 0, 0], EST.step, opts.iters || EST.iters);
    const c = best.car, r1 = v => Math.round(v * 1e4) / 1e4;
    for (const m of ["corner", "straight"]) for (const k of ["CLA_front_m2", "CLA_rear_m2", "CDA_m2"]) c.aero[m][k] = r1(c.aero[m][k]);
    for (const k of ["mu_x", "mu_y", "load_sens"]) c.tyres[k] = r1(c.tyres[k]);
    const r = best.r;
    return {
      method: "MAP (Nelder-Mead, " + (opts.iters || EST.iters) + " iterations) on the pole lap's speed trace + lap time; 4 global parameters with log-normal priors (sigma mu 0.15, CLA 0.3, CDA 0.3, load_sens 0.7)",
      scales: { mu: r1(Math.exp(best.x[0])), cla: r1(Math.exp(best.x[1])), cda: r1(Math.exp(best.x[2])), load_sens: r1(Math.exp(best.x[3])) },
      estimate: { aero: { corner: c.aero.corner, straight: c.aero.straight }, tyres: { mu_x: c.tyres.mu_x, mu_y: c.tyres.mu_y, load_sens: c.tyres.load_sens }, gearing: prior.gearing || null },
      fit_lap: { driver: ref.reference.driver, lap_real_s: ref.reference.lap_s, lap_sim_s: r.lap_s, sectors_real_s: ref.reference.sectors_s, sectors_sim_s: r.sectors_s, trap_real_kmh: ref.reference.speed_trap_kmh, trap_sim_kmh: r.speed_trap_kmh, trace_rms_kmh: Math.round(best.rms * 100) / 100 },
      label: S.LABEL,
    };
  }

  // ---- held-out check: simulate each fitted team car and compare with that team's real lap (telemetry), which was NOT used
  // in any fit except through its lap time and trap (team fit). Node only (reads concept/data/telemetry or a given dir).
  const CORNER_WINDOWS = [["Village T3", 860, 960], ["Loop T4", 990, 1080], ["Brooklands T6", 1940, 2040], ["Luffield T7", 2100, 2220], ["Copse T9", 3000, 3200], ["Becketts T12-13", 3950, 4070], ["Stowe T15", 4960, 5070], ["Vale T16", 5430, 5530], ["Club T17", 5490, 5600]];
  function compareLap(r, ch, tr, lapInfo) {
    // channels on the lap's own 5 m distance grid; positions mapped by lap fraction onto the sim's s frame
    const L = ch.distance_m[ch.distance_m.length - 1], n = r.trace.v_kmh.length;
    const simAt = d => r.trace.v_kmh[Math.min(n - 1, Math.round(((d / L) * tr.L) / tr.ds))];
    let e2 = 0; for (let k = 0; k < ch.distance_m.length; k++) e2 += (simAt(ch.distance_m[k]) - ch.speed_kmh[k]) ** 2;
    const corners = CORNER_WINDOWS.map(([name, a, b]) => {
      let mr = Infinity, ms = Infinity;
      for (let k = 0; k < ch.distance_m.length; k++) { const d = (ch.distance_m[k] / L) * tr.L; if (d >= a && d <= b) { mr = Math.min(mr, ch.speed_kmh[k]); ms = Math.min(ms, simAt(ch.distance_m[k])); } }
      return { corner: name, real_kmh: Math.round(mr * 10) / 10, sim_kmh: Math.round(ms * 10) / 10, diff_kmh: Math.round((ms - mr) * 10) / 10 };
    });
    let vmaxR = 0; for (const v of ch.speed_kmh) vmaxR = Math.max(vmaxR, v);
    return {
      trace_rms_kmh: Math.round(Math.sqrt(e2 / ch.distance_m.length) * 100) / 100,
      sectors_real_s: lapInfo.sector_s, sectors_sim_s: r.sectors_s, sector_residuals_s: r.sectors_s.map((v, i) => Math.round((v - lapInfo.sector_s[i]) * 1000) / 1000),
      vmax_real_kmh: vmaxR, vmax_sim_kmh: r.vmax_kmh, corners,
    };
  }
  function heldOut(fit, dir, opts) {
    const fs = require("fs"), path = require("path");
    dir = dir || path.join(__dirname, "..", "data", "telemetry");
    const tr = T.buildTrack((opts && opts.trackId) || "silverstone"), cond = (opts && opts.conditions) || {};
    const out = [];
    for (const t of fit.teams) {
      const f = path.join(dir, "silverstone-2026-q-" + t.driver.toLowerCase() + ".json");
      if (!fs.existsSync(f)) continue;
      const lap = JSON.parse(fs.readFileSync(f, "utf8"));
      const car = teamCar(t.team, fit), r = S.simulateLap(car, "silverstone", cond, { trace: true, cal: fit.global || { grip_scale: 1, drag_scale: 1 } });
      out.push(Object.assign({ team: t.team, driver: t.driver, used_in_fit: t.driver === fit.reference_driver ? "trace (baseline estimate) + lap + trap" : "lap + trap only" }, compareLap(r, lap.channels, tr, lap.lap)));
    }
    return out;
  }

  // ---- competitor model: MAP fit of (cla_scale, cda_scale) per team and pu_scale per power-unit maker
  function fitTeams(opts) {
    opts = opts || {};
    const trackId = opts.trackId || "silverstone", cond = opts.conditions || {}, cal = opts.cal || S.activeCal();
    const base = opts.car || S.baselineCar(), targets = teamTargets(trackId), sg = TEAM_FIT.sigma, B = TEAM_FIT.bounds;
    const pus = Array.from(new Set(targets.map(t => t.pu))).sort();
    const nT = targets.length, nP = nT * 2 + pus.length;
    const idxPU = t => nT * 2 + pus.indexOf(t.pu);
    const lb = [], ub = [];
    for (let i = 0; i < nT; i++) { lb.push(Math.log(B.cla[0]), Math.log(B.cda[0])); ub.push(Math.log(B.cla[1]), Math.log(B.cda[1])); }
    for (let k = 0; k < pus.length; k++) { lb.push(Math.log(B.pu[0])); ub.push(Math.log(B.pu[1])); }
    let x = new Array(nP).fill(0);
    const sim = (t, i, x) => S.simulateLap(scaledCar(base, { cla_scale: Math.exp(x[2 * i]), cda_scale: Math.exp(x[2 * i + 1]), pu_scale: Math.exp(x[idxPU(t)]) }), trackId, cond, { cal });
    // residual vector: 2 data terms per team, then one prior term per parameter
    function residuals(x, sims) {
      const r = [];
      targets.forEach((t, i) => { const s = sims[i]; r.push((s.lap_s - t.q_s) / sg.lap_s, (s.speed_trap_kmh - t.trap_kmh) / sg.trap_kmh); });
      for (let i = 0; i < nT; i++) r.push(x[2 * i] / sg.cla, x[2 * i + 1] / sg.cda);
      for (let k = 0; k < pus.length; k++) r.push(x[nT * 2 + k] / sg.pu);
      return r;
    }
    const cost = r => r.reduce((p, v) => p + v * v, 0);
    let sims = targets.map((t, i) => sim(t, i, x)), r = residuals(x, sims), c = cost(r), lambda = TEAM_FIT.lambda0, it = 0;
    for (; it < TEAM_FIT.iters; it++) {
      // Jacobian (sparse: team i's two data rows depend on its own two params and its PU's param)
      const J = r.map(() => new Array(nP).fill(0));
      targets.forEach((t, i) => {
        for (const p of [2 * i, 2 * i + 1, idxPU(t)]) {
          const xp = x.slice(); xp[p] += TEAM_FIT.fd; const s = sim(t, i, xp);
          J[2 * i][p] = ((s.lap_s - sims[i].lap_s) / sg.lap_s) / TEAM_FIT.fd;
          J[2 * i + 1][p] = ((s.speed_trap_kmh - sims[i].speed_trap_kmh) / sg.trap_kmh) / TEAM_FIT.fd;
        }
      });
      for (let i = 0; i < nT; i++) { J[2 * nT + 2 * i][2 * i] = 1 / sg.cla; J[2 * nT + 2 * i + 1][2 * i + 1] = 1 / sg.cda; }
      for (let k = 0; k < pus.length; k++) J[4 * nT + k][nT * 2 + k] = 1 / sg.pu;
      const JtJ = [], Jtr = new Array(nP).fill(0);
      for (let a = 0; a < nP; a++) { JtJ.push(new Array(nP).fill(0)); }
      for (let row = 0; row < r.length; row++) for (let a = 0; a < nP; a++) { const ja = J[row][a]; if (!ja) continue; Jtr[a] += ja * r[row]; for (let b = 0; b < nP; b++) JtJ[a][b] += ja * J[row][b]; }
      let accepted = false;
      for (let tries = 0; tries < 6 && !accepted; tries++) {
        const A = JtJ.map((row, a) => row.map((v, b) => (a === b ? v * (1 + lambda) + 1e-9 : v)));
        const d = solve(A, Jtr.map(v => -v));
        const nx = x.map((v, p) => clamp(v + d[p], lb[p], ub[p]));
        const nsims = targets.map((t, i) => sim(t, i, nx)), nr = residuals(nx, nsims), nc = cost(nr);
        if (nc < c) { x = nx; sims = nsims; r = nr; accepted = c - nc < 1e-6 ? "converged" : true; c = nc; lambda = Math.max(lambda / 3, 1e-6); }
        else lambda *= 4;
      }
      if (!accepted || accepted === "converged") break;
    }
    const teams = targets.map((t, i) => ({
      team: t.team, name: t.name, chassis: t.chassis, pu: t.pu, driver: t.driver,
      q_real_s: t.q_s, q_sim_s: sims[i].lap_s, residual_lap_s: +(sims[i].lap_s - t.q_s).toFixed(3),
      trap_real_kmh: t.trap_kmh, trap_sim_kmh: sims[i].speed_trap_kmh, residual_trap_kmh: +(sims[i].speed_trap_kmh - t.trap_kmh).toFixed(1),
      cla_scale: +Math.exp(x[2 * i]).toFixed(4), cda_scale: +Math.exp(x[2 * i + 1]).toFixed(4), pu_scale: +Math.exp(x[idxPU(t)]).toFixed(4),
      at_bound: [2 * i, 2 * i + 1, idxPU(t)].filter(p => Math.abs(x[p] - lb[p]) < 1e-9 || Math.abs(x[p] - ub[p]) < 1e-9).map(p => (p === idxPU(t) ? "pu" : p % 2 ? "cda" : "cla")),
    }));
    const puScale = {}; pus.forEach((p, k) => { puScale[p] = +Math.exp(x[nT * 2 + k]).toFixed(4); });
    return { teams, pu_scale: puScale, iterations: it, cost: +c.toFixed(3), settings: TEAM_FIT, cal, label: S.LABEL };
  }

  function fitted() { return EI.CONCEPT_SIM_FIT || (typeof require === "function" ? require("./fitted.js") : null); }
  // the baseline a fit was made against: the prior car with that fit's estimated parameters
  function baseOf(f) {
    const c = S.priorCar(), e = f && f.baseline_estimate;
    c.id = "baseline-2026"; c.label = "baseline 2026 car (prior + parameters estimated from the 2026 British GP pole lap)";
    if (e) { c.aero.corner = Object.assign({}, e.aero.corner); c.aero.straight = Object.assign({}, e.aero.straight); Object.assign(c.tyres, e.tyres); if (e.gearing) c.gearing = JSON.parse(JSON.stringify(e.gearing)); }
    return c;
  }
  // optional per-team physical overrides derived elsewhere from telemetry, e.g. concept/data/redbull-2026-derived.json
  // (Node only). Expected shape: { "physical_car": { ...partial PhysicalCar... } } - deep-merged over the inferred team car.
  function derivedOverrides(teamId) {
    if (typeof require !== "function") return null;
    try {
      const fs = require("fs"), path = require("path"), f = path.join(__dirname, "..", "data", teamId + "-2026-derived.json");
      if (!fs.existsSync(f)) return null;
      const j = JSON.parse(fs.readFileSync(f, "utf8"));
      return j && typeof j.physical_car === "object" ? j.physical_car : null;
    } catch (e) { return null; }
  }
  function deepMerge(a, b) { for (const k of Object.keys(b)) { if (b[k] && typeof b[k] === "object" && !Array.isArray(b[k]) && a[k] && typeof a[k] === "object") deepMerge(a[k], b[k]); else a[k] = b[k]; } return a; }
  function teamCar(teamId, fit) {
    const f = fit || fitted(), t = f && f.teams && f.teams.find(x => x.team === teamId);
    if (!t) throw new Error("concept sim: no fitted car for team " + teamId);
    const c = scaledCar(baseOf(f), t, { id: "team-" + t.team, label: t.name + " (inferred from public 2026 British GP qualifying lap + speed trap; not team data)" });
    const o = !fit && derivedOverrides(teamId);
    if (o) { deepMerge(c, JSON.parse(JSON.stringify(o))); c.label = t.name + " (inferred car + telemetry-derived overrides from concept/data/" + teamId + "-2026-derived.json)"; }
    return c;
  }
  function teamCars(fit) { const f = fit || fitted(); return f.teams.map(t => teamCar(t.team, f)); }

  const api = { baseOf, derivedOverrides, TEAM_FIT, EST, CORNER_WINDOWS, reference, teamTargets, scaledCar, calibrate, fitTeams, heldOut, compareLap, traceError, teamCar, teamCars, fitted };
  EI.conceptSimFit = api;
  if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
