#!/usr/bin/env node
// PURPLE concept - regenerates concept/sim/fitted-tracks.js: the multi-track calibration (docs/concept/SIM.md "Multi-track").
// Per circuit: the shared track grip, each team's wing level and the shared trap bias (multitrack.fitTrack), the held-out check
// (multitrack.heldOutTrack) and, for information, the RB22's lap-time-optimal wing level against its fitted one.
// Usage: node concept/sim/build-fit-tracks.js [monza monaco spa hungaroring] [--check]   (~10-20 s per circuit, deterministic)
// Circuits not named keep their stored fit. --check exits non-zero if the stored file differs from a fresh build.
"use strict";
const fs = require("fs"), path = require("path");
const M = require("./multitrack.js"), SU = require("./setup.js"), S = require("./lapsim.js"), F = require("./fit.js");
const OUT = path.join(__dirname, "fitted-tracks.js");
const args = process.argv.slice(2), check = args.includes("--check");
const named = args.filter(a => !a.startsWith("-"));
const ALL = M.CIRCUITS.filter(c => c !== "silverstone");
const list = named.length ? named : ALL;
const prev = fs.existsSync(OUT) ? require(OUT) : null;
const tracks = {};
for (const id of ALL) if (prev && prev.tracks && prev.tracks[id] && !list.includes(id)) tracks[id] = prev.tracks[id];
const r2 = v => Math.round(v * 100) / 100;
for (const id of list) {
  const t0 = Date.now(), fit = M.fitTrack(id), held = M.heldOutTrack(fit, id);
  const rb = SU.setupCar(F.teamCar("redbull"), { wing_deg: 0 }), opt = M.optimalWing(rb, id, undefined, { track_grip: fit.grip });
  const rbRow = fit.teams.find(t => t.team === "redbull");
  tracks[id] = {
    circuit: id, grip: fit.grip, trap_bias_kmh: fit.trap_bias_kmh, iterations: fit.iterations, cost: fit.cost,
    conditions: S.defaultConditions(id), energy: { recharge_q_mj: S.PU_SECTORS[id].recharge_q_mj, rate_kw_s: S.PU_SECTORS[id].rate_kw_s, curve: S.PU_SECTORS[id].curve_name || S.PU_SECTORS[id].curve, source: S.PU_SECTORS[id].source },
    our_driver: M.ourDriver(id),
    teams: fit.teams,
    redbull_optimal_wing: { wing_deg: opt.wing_deg, lap_s: opt.lap_s, fitted_wing_deg: rbRow.wing_deg, fitted_lap_s: rbRow.q_sim_s },
    heldout: { basis: held.basis, summary: held.summary, rows: held.rows.map(r => ({ team: r.team, fitted: r.fitted, teammate: r.teammate })) },
  };
  console.log(id, "grip", fit.grip, "trap bias", fit.trap_bias_kmh, "max |lap res|", Math.max(...fit.teams.map(t => Math.abs(t.residual_lap_s))), "held-out", JSON.stringify(held.summary), ((Date.now() - t0) / 1000).toFixed(1) + " s");
}
const order = ALL.filter(id => tracks[id]), ordered = {}; for (const id of order) ordered[id] = tracks[id];
const DATA = {
  generated_by: "concept/sim/build-fit-tracks.js",
  method: "per circuit, MAP (Levenberg-Marquardt) of one shared track grip factor, one wing level per team (concept/sim/setup.js, the aero map's trade-off curve) and one shared trap bias on each team's best valid qualifying lap (sigma 0.10 s) and session-maximum speed trap (2.5 km/h); Red Bull on the RB22's calibration driver (HAD; LAW at Monza). Every car keeps its 2026 British GP physics (fitted.js).",
  wing_curve_source: SU.wingCurve().source,
  tracks: ordered,
};
const body = "// GENERATED by concept/sim/build-fit-tracks.js - do not edit by hand. Multi-track calibration of the PURPLE concept lap sim (docs/concept/SIM.md \"Multi-track\").\n(function () {\n  const FIT = " + JSON.stringify(DATA) + ";\n" +
  "  const root = typeof window !== \"undefined\" ? window : globalThis;\n  root.EI = root.EI || {}; root.EI.CONCEPT_SIM_TRACK_FIT = FIT;\n" +
  "  if (typeof module !== \"undefined\" && module.exports) module.exports = FIT;\n})();\n";
if (check) {
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8") === body;
  console.log(same ? "fitted-tracks.js is up to date" : "fitted-tracks.js is STALE"); process.exit(same ? 0 : 1);
}
fs.writeFileSync(OUT, body);
console.log("wrote concept/sim/fitted-tracks.js", (body.length / 1024).toFixed(1) + " KB", order.join(", "));
