// PURPLE concept - writes concept/sim/team-overrides.js: the per-team physical overrides concept/sim/fit.js derivedOverrides() reads
// from concept/data/<team>-2026.json and the RB22 data sheet with fs (Node only), as a plain browser data file. Without it a page
// that runs the physics sim in the browser (the concept race page) laps a different RB22 anchor than the engine (Node): mass, gear
// ratios, roll-stiffness split. The demo's best car lapped 87.815 s in the browser against the engine's 87.700 s.
// Run: node concept/sim/build-team-overrides.js   (test/concept-race-quali.test.js fails if the file drifts from fit.js)
const fs = require("fs"), path = require("path");
const fit = require("./fit.js"), fitted = require("./fitted.js");
const f = (globalThis.EI && globalThis.EI.CONCEPT_SIM_FIT) || fitted;
function build() {
  const out = {};
  for (const t of (f && f.teams) || []) { const o = fit.derivedOverrides(t.team); if (o) out[t.team] = o; }
  return out;
}
function source(o) {
  return "// PURPLE concept - GENERATED by concept/sim/build-team-overrides.js from concept/data/<team>-2026.json + the RB22 data sheet: the\n" +
    "// per-team overrides concept/sim/fit.js derivedOverrides() reads with fs in Node, for pages that run the physics sim in the browser.\n" +
    "// Do not edit; re-run the builder after a data change.\n" +
    "(function () { const root = typeof window !== \"undefined\" ? window : globalThis; const EI = (root.EI = root.EI || {});\n" +
    "  EI.CONCEPT_SIM_TEAM_OVERRIDES = " + JSON.stringify(o) + ";\n" +
    "  if (typeof module !== \"undefined\" && module.exports) module.exports = EI.CONCEPT_SIM_TEAM_OVERRIDES;\n})();\n";
}
if (require.main === module) {
  const file = path.join(__dirname, "team-overrides.js"), o = build();
  fs.writeFileSync(file, source(o));
  console.log("wrote " + file + " (" + Object.keys(o).join(", ") + ")");
}
module.exports = { build, source };
